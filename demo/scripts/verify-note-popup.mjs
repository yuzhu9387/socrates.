import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const browser=await chromium.launch({headless:true,executablePath:'/Users/guoyuzhu/Library/Caches/ms-playwright/chromium_headless_shell-1228/chrome-headless-shell-mac-arm64/chrome-headless-shell'});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('socrates-uiux-v1')));
const verifyPopup=async(width)=>{
 const dialog=page.getByRole('dialog',{name:'New note',exact:true});
 await dialog.waitFor();
 await page.waitForTimeout(250);
 const box=await dialog.boundingBox();
 assert.ok(Math.abs(box.x+box.width/2-width/2)<2,'Composer is centered horizontally');
 assert.ok(box.x>=14,'Composer is inset from the screen edge');
 assert.equal(await dialog.evaluate(el=>el.classList.contains('drawer')),false);
 assert.equal(await page.locator('#note-summary').evaluate(el=>document.activeElement===el),true);
 return dialog;
};
try{
 await page.goto('http://127.0.0.1:4173/#/dashboard');
 await page.waitForLoadState('networkidle');
 const initial=await state();
 assert.equal(await page.locator('.brand .socrates-mark').count(),1);
 await page.locator('.brand').screenshot({path:new URL('../screenshots/socrates-wordmark.png',import.meta.url).pathname});
 await page.getByRole('button',{name:'New note',exact:false}).first().click();
 let dialog=await verifyPopup(1440);
 await dialog.getByRole('button',{name:'Save note',exact:false}).click();
 await dialog.getByRole('alert').getByText('Add a one-line summary to save this note.').waitFor();
 await dialog.locator('#note-summary').fill('念念相连 · Connected thoughts');
 await dialog.locator('#note-tag').fill('复盘 reflection');
 await dialog.locator('#note-tag').press('Enter');
 await dialog.locator('#note-body').fill('今天发现：一个问题，可以连接两个想法。\n\n**A thought becomes an insight.**');
 await dialog.getByRole('button',{name:'Preview',exact:true}).click();
 await dialog.getByText('A thought becomes an insight.',{exact:true}).waitFor();
 await page.screenshot({path:new URL('../screenshots/note-popup.png',import.meta.url).pathname});
 await dialog.getByRole('button',{name:'Save note',exact:false}).click();
 const after=await state();
 assert.equal(after.notes.length,initial.notes.length+1);
 const note=after.notes.find(n=>n.summary==='念念相连 · Connected thoughts');
 assert.ok(note.body.includes('今天发现')&&note.tags.includes('复盘 reflection'));
 checks.push('Desktop centered composer, summary focus, validation, bilingual note/tag/body, Markdown preview and save');
 await page.getByRole('button',{name:`Open note ${note.summary}`,exact:true}).click();
 assert.equal(await page.getByRole('dialog').evaluate(el=>el.classList.contains('drawer')),true);
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 checks.push('Existing note detail still opens correctly');
 await page.goto('http://127.0.0.1:4173/#/brainstorm/map-expression');
 await page.getByRole('button',{name:'New insight',exact:true}).click();
 dialog=await verifyPopup(1440);
 await dialog.locator('#note-summary').fill('新的启发 · New insight');
 const beforeBoard=await state();
 await dialog.getByRole('button',{name:'Save note',exact:false}).click();
 const afterBoard=await state();
 const insight=afterBoard.notes.find(n=>n.summary==='新的启发 · New insight');
 assert.ok(afterBoard.maps.find(m=>m.id==='map-expression').nodes.some(n=>n.noteId===insight.id));
 assert.equal(afterBoard.maps.find(m=>m.id==='map-expression').nodes.length,beforeBoard.maps.find(m=>m.id==='map-expression').nodes.length+1);
 checks.push('Board New insight opens centered popup and saves one source note plus one board card');
 await page.waitForTimeout(3600);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'New insight',exact:true}).click();
 dialog=await verifyPopup(390);
 await page.screenshot({path:new URL('../screenshots/note-popup-mobile.png',import.meta.url).pathname});
 await dialog.getByRole('button',{name:'Save note',exact:false}).focus();
 await page.keyboard.press('Tab');
 assert.equal(await dialog.getByRole('button',{name:'Close dialog',exact:true}).evaluate(el=>document.activeElement===el),true);
 await page.keyboard.press('Shift+Tab');
 assert.equal(await dialog.getByRole('button',{name:'Save note',exact:false}).evaluate(el=>document.activeElement===el),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 assert.deepEqual((await state()).notes,afterBoard.notes);
 checks.push('Mobile inset popup, keyboard focus trap, Escape dismissal without creating data');
 assert.deepEqual(errors,[]);
 const result={checks,errors};
 await fs.writeFile(new URL('../screenshots/note-popup-results.json',import.meta.url),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));
}finally{await context.close();await browser.close();}
